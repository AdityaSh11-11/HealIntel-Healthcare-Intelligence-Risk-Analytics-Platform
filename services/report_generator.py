def ai_summary_page(elements):

    elements.append(Paragraph("AI Executive Healthcare Summary", SECTION))

    report = generate_ai_report(provider="Gemini")

    report = report.replace("\n","<br/>")

    elements.append(
        Paragraph(report, SMALL)
    )

    elements.append(PageBreak())

# ----------------------------------------------------------
# ANALYTICS PAGE
# ----------------------------------------------------------

def analytics_page(elements, snapshot):

    pages = [
        ("Top Diseases", snapshot["disease"]),
        ("Top Hospitals", snapshot["hospital"]),
        ("Top Doctors", snapshot["doctor"]),
        ("Insurance Performance", snapshot["insurance"])
    ]

    for title, df in pages:

        elements.append(Paragraph(title, SECTION))
        elements.append(dataframe_table(df))
        elements.append(Spacer(1,25))

    elements.append(PageBreak())

