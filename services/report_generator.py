# KPI PAGE
# ----------------------------------------------------------

def kpi_page(elements, kpi_df):

    k = kpi_df.iloc[0]

    elements.append(Paragraph("Executive KPI Overview", SECTION))

    metrics = [
        ["Metric","Value"],
        ["Total Patients", f"{int(k.total_patients):,}"],
        ["Total Revenue", f"${k.total_revenue:,.2f}"],
        ["Average Age", str(k.avg_age)],
        ["Average Stay", f"{k.avg_stay} Days"]
    ]

    table = Table(metrics, colWidths=[220,220])

    table.setStyle(TableStyle([
        ("BACKGROUND",(0,0),(-1,0),colors.HexColor("#1D4ED8")),
        ("TEXTCOLOR",(0,0),(-1,0),colors.white),
        ("FONTNAME",(0,0),(-1,0),"Helvetica-Bold"),
        ("BACKGROUND",(0,1),(-1,-1),colors.HexColor("#EFF6FF")),
        ("GRID",(0,0),(-1,-1),0.4,colors.grey),
        ("BOTTOMPADDING",(0,0),(-1,0),12)
    ]))

    elements.append(table)
    elements.append(PageBreak())

