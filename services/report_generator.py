def generate_pdf_report():

    snapshot = warehouse_snapshot()

    os.makedirs("reports", exist_ok=True)

    filename = (
        "reports/"
        f"Healthcare_AI_Report_{datetime.now().strftime('%Y%m%d_%H%M')}.pdf"
    )

    doc = SimpleDocTemplate(
        filename,
        pagesize=A4,
        rightMargin=35,
        leftMargin=35,
        topMargin=35,
        bottomMargin=30
    )

    elements = []

    cover(elements)

    kpi_page(elements, snapshot["kpi"])

    ai_summary_page(elements)

    analytics_page(elements, snapshot)

    recommendation_page(elements)

    appendix(elements)

    doc.build(elements)

    return filename


