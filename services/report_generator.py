def query(sql):
    return pd.read_sql(sql, engine)


def warehouse_snapshot():

    kpi = query("""
    SELECT
        COUNT(*) total_patients,
        ROUND(SUM(billing_amount),2) total_revenue,
        ROUND(AVG(age),1) avg_age,
        ROUND(AVG(length_of_stay),1) avg_stay
    FROM fact_patients
    """)

    disease = query("""
    SELECT
        medical_condition,
        COUNT(*) patients,
        ROUND(AVG(billing_amount),2) avg_bill
    FROM fact_patients
    GROUP BY medical_condition
    ORDER BY patients DESC
    LIMIT 10
    """)

    hospital = query("""
    SELECT
        dh.hospital_name,
        COUNT(*) patients,
        ROUND(SUM(fp.billing_amount),2) revenue
    FROM fact_patients fp
    JOIN dim_hospital dh USING(hospital_id)
    GROUP BY dh.hospital_name
    ORDER BY revenue DESC
    LIMIT 10
    """)

    insurance = query("""
    SELECT
        di.insurance_provider,
        COUNT(*) claims,
        ROUND(SUM(fp.billing_amount),2) billing
    FROM fact_patients fp
    JOIN dim_insurance di USING(insurance_id)
    GROUP BY di.insurance_provider
    ORDER BY billing DESC
    """)

    doctors = query("""
    SELECT
        dd.doctor_name,
        COUNT(*) patients
    FROM fact_patients fp
    JOIN dim_doctor dd USING(doctor_id)
    GROUP BY dd.doctor_name
    ORDER BY patients DESC
    LIMIT 10
    """)

    return {
        "kpi": kpi,
        "disease": disease,
        "hospital": hospital,
        "insurance": insurance,
        "doctor": doctors
    }

